// Generate the workshop zine's table of contents and per-page prev/next nav
// bars from a single manifest, so reordering or renaming a page is a one-file
// edit instead of hand-editing 28 HTML files.
//
// Source of truth: workshop/zine.manifest.json
//   - The index TOC (5 acts) + the "Start reading" CTA on index.html
//   - The <nav class="page-nav"> prev/next bar on every Part-*.html page
//
// The generated regions are wrapped in HTML comment markers
// (WORKSHOP-TOC / WORKSHOP-NAV). On the first run the script finds the existing
// blocks and wraps them; afterwards it rewrites between the markers. Everything
// else on each page (including its custom <footer>) is left untouched.
//
// The workshop/ zine is gitignored and never published; this script only edits
// files in place.
//
// Usage:
//   npm run build:workshop-nav     regenerate index TOC + every page nav bar
//   npm run lint:workshop-nav      check-only: fail if the manifest and the
//                                  generated HTML have drifted (no writes)
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const checkMode = process.argv.includes('--check');
const workshopDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'workshop');
const manifest = JSON.parse(readFileSync(join(workshopDir, 'zine.manifest.json'), 'utf8'));

const GEN_NOTE = 'generated by scripts/build-workshop-nav.mjs — edit workshop/zine.manifest.json instead';

// Minimal HTML text escape. The manifest uses plain apostrophes/dashes that are
// valid in HTML text, so only the markup-significant characters are escaped.
function esc(text) {
  return String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

// Flat, ordered list of every page with its 1-based sequence number.
const pages = manifest.acts.flatMap((act) => act.pages);
pages.forEach((page, i) => { page.num = i + 1; });
const total = pages.length;
const pad = (n) => String(n).padStart(2, '0');

const contents = manifest.contents;
const navAria = manifest.navAriaLabel;

// --- index.html: TOC + start CTA ------------------------------------------
function buildToc() {
  const lines = [];
  lines.push(`    <!-- WORKSHOP-TOC:START (${GEN_NOTE}) -->`);
  for (const act of manifest.acts) {
    lines.push(`    <nav class="toc-group" aria-label="${esc(act.aria)}">`);
    lines.push('      <div class="toc-head">');
    lines.push(`        <span class="act">${esc(act.roman)}</span>`);
    lines.push(`        <h2>${esc(act.title)}</h2>`);
    lines.push('      </div>');
    lines.push('');
    for (const page of act.pages) {
      const tagClass = page.tagClass ? ` ${esc(page.tagClass)}` : '';
      lines.push(`      <a class="toc-entry" href="${esc(page.file)}">`);
      lines.push(`        <span class="te-num">${pad(page.num)}</span>`);
      lines.push(`        <span class="te-title">${esc(page.title)}<span class="te-q">${esc(page.q)}</span></span>`);
      lines.push(`        <span class="te-tag${tagClass}">${esc(page.tag)}</span>`);
      lines.push('      </a>');
    }
    lines.push('    </nav>');
    lines.push('');
  }
  const first = pages[0];
  lines.push(`    <a class="start-cta" href="${esc(first.file)}">${esc(manifest.startCta.lead)} · ${esc(manifest.startCta.prefix)} ${pad(first.num)} →</a>`);
  lines.push('    <!-- WORKSHOP-TOC:END -->');
  return lines.join('\n');
}

// --- Part-*.html: prev/next nav bar ---------------------------------------
function buildPageNav(page) {
  const prev = page.num === 1
    ? { href: contents.file, label: contents.label }
    : { href: pages[page.num - 2].file, label: pages[page.num - 2].nav };
  const next = page.num === total
    ? { href: contents.file, label: `${contents.label} · All ${total} parts` }
    : { href: pages[page.num].file, label: pages[page.num].nav };
  return [
    `<!-- WORKSHOP-NAV:START (${GEN_NOTE}) -->`,
    `<nav class="page-nav" aria-label="${esc(navAria)}">`,
    `  <a href="${esc(prev.href)}" rel="prev" class="prev-pill">Prev · ${esc(prev.label)}</a>`,
    `  <a href="${esc(next.href)}" rel="next" class="next-pill">Next · ${esc(next.label)}</a>`,
    '</nav>',
    '<!-- WORKSHOP-NAV:END -->',
  ].join('\n');
}

// Replace either an existing markered region or the first bare block. The
// leading-whitespace group keeps the file indentation consistent on rewrite.
function replaceRegion(html, markerName, bareRegex, replacement, label) {
  const markered = new RegExp(`[ \\t]*<!-- ${markerName}:START[\\s\\S]*?${markerName}:END -->`);
  if (markered.test(html)) return html.replace(markered, replacement);
  if (bareRegex.test(html)) return html.replace(bareRegex, replacement);
  throw new Error(`Could not find ${markerName} region (no markers and no existing block) in ${label}`);
}

// --- structural validation (manifest <-> disk parity) ---------------------
// These checks run in both modes; in build mode they fail fast before writing
// so a typo in the manifest can never half-apply across 28 files.
const problems = [];
const manifestFiles = pages.map((page) => page.file);

// Duplicate entries in the manifest.
const seen = new Set();
for (const file of manifestFiles) {
  if (seen.has(file)) problems.push(`manifest lists "${file}" more than once`);
  seen.add(file);
}

// Manifest entries that do not exist on disk.
const onDisk = new Set(
  readdirSync(workshopDir).filter((name) => /^Part-.*\.html$/.test(name)),
);
for (const file of manifestFiles) {
  if (!onDisk.has(file)) problems.push(`manifest references "${file}" but no such file exists`);
}

// Part-*.html files on disk that the manifest forgot.
for (const file of onDisk) {
  if (!seen.has(file)) problems.push(`"${file}" exists on disk but is missing from the manifest`);
}

// --- compute desired output for each target -------------------------------
const targets = [
  {
    path: join(workshopDir, 'index.html'),
    label: 'index.html',
    marker: 'WORKSHOP-TOC',
    bare: /[ \t]*<nav class="toc-group"[\s\S]*<a class="start-cta"[^>]*>[\s\S]*?<\/a>/,
    replacement: buildToc(),
  },
  ...pages.map((page) => ({
    path: join(workshopDir, page.file),
    label: page.file,
    marker: 'WORKSHOP-NAV',
    bare: /[ \t]*<nav class="page-nav"[\s\S]*?<\/nav>/,
    replacement: buildPageNav(page),
  })),
];

// Only process targets that still exist (structural problems already recorded).
const usableTargets = targets.filter((target) => {
  if (target.label === 'index.html') return true;
  return onDisk.has(target.label);
});

if (checkMode) {
  let stale = 0;
  for (const target of usableTargets) {
    const current = readFileSync(target.path, 'utf8');
    let updated;
    try {
      updated = replaceRegion(current, target.marker, target.bare, target.replacement, target.label);
    } catch (err) {
      problems.push(err.message);
      continue;
    }
    if (updated !== current) {
      stale += 1;
      problems.push(`${target.label} is out of date (run \`npm run build:workshop-nav\`)`);
    }
  }
  if (problems.length > 0) {
    console.error(`workshop nav drift check FAILED (${problems.length} issue(s)):`);
    for (const problem of problems) console.error(`  - ${problem}`);
    process.exit(1);
  }
  console.log(`workshop nav drift check passed (${usableTargets.length} files, ${stale} stale).`);
  process.exit(0);
}

// build mode
if (problems.length > 0) {
  console.error(`Refusing to write — fix these manifest/disk issues first:`);
  for (const problem of problems) console.error(`  - ${problem}`);
  process.exit(1);
}

let changed = 0;
for (const target of usableTargets) {
  const current = readFileSync(target.path, 'utf8');
  const updated = replaceRegion(current, target.marker, target.bare, target.replacement, target.label);
  writeFileSync(target.path, updated);
  changed += 1;
}
console.log(`updated ${changed} files (index TOC + ${pages.length} page nav bars across ${manifest.acts.length} acts)`);
console.log('Done. Source of truth: workshop/zine.manifest.json');
